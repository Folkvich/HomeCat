-- ===== ห้ามแมวชื่อซ้ำกันในบ้านเดียวกัน =====
-- ไม่สนตัวพิมพ์เล็ก/ใหญ่ และช่องว่างหัวท้าย ("ส้ม", " ส้ม ", "SOM"/"som" ถือว่าซ้ำกัน)
-- หน้าเว็บเช็กก่อนบันทึกอยู่แล้ว ตัวนี้กันกรณีคนในบ้าน 2 คนเพิ่มชื่อเดียวกันพร้อมกัน
create unique index cats_unique_name_per_household
  on public.cats (household_id, lower(trim(name)));
